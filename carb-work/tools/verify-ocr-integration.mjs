import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const dist = path.resolve('carb-work/overlay/asar/node_modules/@harness/server/dist');
const { carbOcrAttachments } = await import(pathToFileURL(path.join(dist, 'carb-ocr.js')));
const { selectDesignMode } = await import(pathToFileURL(path.join(dist, 'carb-design-fallback.js')));
const image = process.env.CARB_OCR_TEST_IMAGE;
assert(image && path.isAbsolute(image), 'Set CARB_OCR_TEST_IMAGE to a local screenshot containing readable text.');
const result = await carbOcrAttachments([image]);
assert.match(result, /Local OCR extracted/);
assert.doesNotMatch(result, /Local OCR failed|No text detected/);
assert.match(await carbOcrAttachments(['C:/missing-carb-image.png']), /OCR failed/);
assert.equal(await carbOcrAttachments(['C:/example.md']), '');
const brief = p => p === 'brief';
assert.deepEqual(selectDesignMode(['brief', image], brief, false), { design: false, textOnly: true, blocked: false, attachments: [image] });
assert.equal(selectDesignMode(['brief', image], brief, true).design, true);
assert.equal(selectDesignMode([image], brief, false).textOnly, false);
const source = await readFile(path.join(dist, 'orchestrator.js'), 'utf8');
assert.match(source, /entry\.session\.capabilities\.images \? '' : await carbOcrAttachments\(attachments\)/);
assert.match(source, /session\.capabilities\.images \? '' : await carbOcrAttachments\(item\.attachments\)/);
assert.match(source, /session\.steer\(threadId, steerText, item\.attachments\)/);
assert.match(source, /entry\.session\.sendTurn\(threadId, sent, attachments, options\)/);
console.log('OCR real screenshot, failures, design fallback and normal/steer integration passed.');
